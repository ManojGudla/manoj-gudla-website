/*
 * Version 3 upgrade for the live database: removes the BCA entry, adds
 * maNOWj GeoIntel as a project and takes the long dashes out of text that
 * was already saved. Safe to run more than once.
 */
const dashFixes: [string, string][] = [
  ["Manoj Kumar Gudla — Technology Professional", "Manoj Kumar Gudla | Technology Professional"],
  ["innovation roles — where curiosity", "innovation roles, where curiosity"],
  ["emerging tools — and the lifestyle", "emerging tools, and the lifestyle"],
  ["independent products — from first idea", "independent products, from first idea"],
  ["platforms early — and figuring out", "platforms early and figuring out"],
  ["professionals — and learning from", "professionals and learning from"],
  ["AI and ML — from emerging tools", "AI and ML, from emerging tools"],
  [" — ", ", "],
  ["—", ", "],
];
const contentTables = [
  "profile", "site_settings", "experience", "education", "skills", "certifications", "projects",
  "project_images", "creator_content", "creator_stats", "achievements", "interests", "gallery",
  "vision_items", "resources", "resource_packs", "resource_pack_items", "services", "media",
];
const v3 = [
  "-- =====================================================================",
  "-- UPGRADE to version 3. Paste this whole file into Supabase → SQL Editor",
  "-- and click Run. Safe to run more than once.",
  "-- GENERATED by scripts/generate-seed-sql.ts. Do not edit by hand.",
  "-- =====================================================================",
  "",
  "-- 1. Remove the BCA entry",
  "delete from public.education where institution ilike '%Aditya Degree College%' or qualification ilike 'Bachelor of Computer Applications%';",
  "",
  "-- 2. Add maNOWj GeoIntel as a project (kept as it is if it already exists)",
  inserts("projects", seed.seedProjects as unknown as Row[]),
  "-- 3. Replace long dashes in saved text",
  "do $$",
  "declare c record; f text[]; fixes text[][] := array[",
  dashFixes.map(([a, b]) => `  [${lit(a)}, ${lit(b)}]`).join(",\n"),
  "];",
  "begin",
  "  for c in select table_name, column_name from information_schema.columns",
  "    where table_schema = 'public' and data_type in ('text', 'character varying')",
  `      and table_name = any (array[${contentTables.map((t) => lit(t)).join(", ")}])`,
  "  loop",
  "    foreach f slice 1 in array fixes loop",
  "      execute format('update public.%I set %I = replace(%I, $1, $2) where %I like ''%%'' || $1 || ''%%''',",
  "        c.table_name, c.column_name, c.column_name, c.column_name) using f[1], f[2];",
  "    end loop;",
  "  end loop;",
  "end $$;",
  "",
].join("\n");
const v3Target = join(process.cwd(), "supabase", "upgrade-v3.sql");
writeFileSync(v3Target, v3);
console.log(`Wrote ${v3Target}`);
